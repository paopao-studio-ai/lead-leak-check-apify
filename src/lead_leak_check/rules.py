"""Rule engine: turn a lead-pipeline description into a ranked list of leak risks.

Every field is tri-state: True (in place), False (missing), None (not stated).
A missing safeguard yields the rule's severity; an unstated one yields a lower
"verify" finding, so an incomplete description never reads as a clean bill of health.
"""
from __future__ import annotations

import csv
import io
import re
import statistics
from dataclasses import dataclass, asdict, field
from datetime import datetime, timezone
from typing import Any, Callable

SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2, "verify": 3}
LANDING_URL = "https://paopao-studio.pages.dev/?utm_source=apify&utm_medium=actor&utm_campaign=lead_leak_1029"


@dataclass
class Finding:
    id: str
    severity: str
    title: str
    why: str
    fix: str
    evidence: str = ""

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class Report:
    pipeline: str
    findings: list[Finding] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def score(self) -> int:
        """0 = no known risk, 100 = leaking everywhere."""
        w = {"high": 22, "medium": 10, "low": 4, "verify": 3}
        return min(100, sum(w[f.severity] for f in self.findings))

    def as_dict(self) -> dict[str, Any]:
        fs = sorted(self.findings, key=lambda f: SEVERITY_ORDER[f.severity])
        return {
            "pipeline": self.pipeline,
            "risk_score": self.score,
            "counts": {s: sum(1 for f in fs if f.severity == s) for s in SEVERITY_ORDER},
            "findings": [f.as_dict() for f in fs],
            "notes": self.notes,
            "report_markdown": self.markdown(),
        }

    def markdown(self) -> str:
        fs = sorted(self.findings, key=lambda f: SEVERITY_ORDER[f.severity])
        out = [f"# Lead leak risk: {self.pipeline}", "", f"Risk score: **{self.score}/100** ({len(fs)} findings)", ""]
        if not fs:
            out.append("No leak risks found in the information given.")
        for i, f in enumerate(fs, 1):
            out += [f"## {i}. [{f.severity.upper()}] {f.title}", f"- Why it leaks: {f.why}", f"- Fix: {f.fix}"]
            if f.evidence:
                out.append(f"- Evidence: {f.evidence}")
            out.append("")
        for n in self.notes:
            out.append(f"> {n}")
        out += ["", f"_Generated by lead-leak-check (MIT). Want a human to map the full pipeline? {LANDING_URL}_"]
        return "\n".join(out).strip() + "\n"


def _get(cfg: dict, path: str) -> Any:
    cur: Any = cfg
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur


@dataclass
class Rule:
    id: str
    severity: str
    title: str
    why: str
    fix: str
    check: Callable[[dict], bool | None]  # True=safe, False=risk, None=unknown


def _bool(path: str) -> Callable[[dict], bool | None]:
    def f(cfg: dict) -> bool | None:
        v = _get(cfg, path)
        return None if v is None else bool(v)
    return f


def _owner(cfg: dict) -> bool | None:
    v = _get(cfg, "routing.owner_assignment")
    if v is None:
        return None
    return str(v).lower() not in {"none", "", "false", "shared", "channel", "nobody"}


def _sla(cfg: dict) -> bool | None:
    v = _get(cfg, "response.sla_minutes")
    if v is None:
        return None
    try:
        return 0 < float(v) <= 60
    except (TypeError, ValueError):
        return False


def _storage(cfg: dict) -> bool | None:
    v = _get(cfg, "storage.type")
    if v is None:
        return None
    return str(v).lower() not in {"none", "inbox", "email_only", ""}


def _ai_send(cfg: dict) -> bool | None:
    if _get(cfg, "response.ai_drafts") is False:
        return True  # rule not applicable
    if _get(cfg, "response.ai_drafts") is None:
        return True
    v = _get(cfg, "response.human_send_step")
    return None if v is None else bool(v)


def _required_fields(cfg: dict) -> bool | None:
    srcs = cfg.get("sources")
    if not isinstance(srcs, list) or not srcs:
        return None
    forms = [s for s in srcs if isinstance(s, dict) and str(s.get("type", "")).lower() in {"web_form", "form", "ads_lead_form", "typeform", "tally"}]
    if not forms:
        return True
    vals = [s.get("required_contact_field") for s in forms]
    if any(v is False for v in vals):
        return False
    if any(v is None for v in vals):
        return None
    return True


def _tz(cfg: dict) -> bool | None:
    b, s = _get(cfg, "timezone.business_tz"), _get(cfg, "timezone.automation_tz")
    if b is None or s is None:
        return None
    return str(b).strip().lower() == str(s).strip().lower()


def _free_plan(cfg: dict) -> bool | None:
    v = _get(cfg, "automation.plan")
    if v is None:
        return None
    return str(v).lower() not in {"free", "starter_free", "trial"}


def _chat_sources(cfg: dict) -> bool | None:
    srcs = cfg.get("sources")
    if not isinstance(srcs, list):
        return None
    chats = [s for s in srcs if isinstance(s, dict) and str(s.get("type", "")).lower() in {"whatsapp", "instagram_dm", "facebook_dm", "chat", "telegram", "line", "kakaotalk"}]
    if not chats:
        return True
    vals = [s.get("logged_to_storage") for s in chats]
    if any(v is False for v in vals):
        return False
    if any(v is None for v in vals):
        return None
    return True


RULES: list[Rule] = [
    Rule("no-owner", "high", "Nobody owns the first reply",
         "Leads posted to a shared sheet or channel are seen by everyone and answered by no one.",
         "Assign an owner per lead (round robin or fixed) at the moment it is created, and name them in the notification.", _owner),
    Rule("no-sla-alert", "high", "No alert when a lead goes unanswered",
         "Automations report Success when the lead is stored; nothing checks that a human replied.",
         "Add a heartbeat: every 5-15 min, flag leads older than the SLA with no first-response timestamp (see the free n8n 'missed-lead heartbeat' template).", _bool("monitoring.unanswered_lead_alert")),
    Rule("no-error-alert", "high", "Failed or disabled automations are silent",
         "Expired connections, plan limits or a teammate's edit can switch a workflow off with no notification.",
         "Turn on error notifications (Zapier/Make/n8n error workflow) to a channel someone watches, and alert when no run happened in the expected window.", _bool("monitoring.error_alerts")),
    Rule("no-sla", "medium", "No response-time target",
         "Without an SLA there is no definition of 'late', so nothing can be alerted on.",
         "Set a first-response target in minutes (15-60 for inbound leads) and store first_response_at on every lead.", _sla),
    Rule("no-storage", "high", "Leads live only in an inbox or chat app",
         "If the lead is never written to a sheet or CRM there is no list to check, follow up or report on.",
         "Write every lead to one system of record (sheet/CRM) with created_at, owner, status, first_response_at.", _storage),
    Rule("chat-not-logged", "high", "Chat leads (WhatsApp/DM) are not logged",
         "Messages that stay in a phone app never reach the sheet or CRM, so no alert can see them.",
         "Log chat conversations to the system of record via the platform's API/webhook or a shared inbox tool.", _chat_sources),
    Rule("silent-filters", "medium", "Form fields can be empty and filters stop quietly",
         "A missing email/phone or a renamed form field sends runs down a branch that ends without an error.",
         "Make one contact field required, and route filtered-out leads to a 'needs review' list instead of stopping.", _required_fields),
    Rule("ai-draft-unsent", "medium", "AI drafts replies but nobody is told to send them",
         "Drafts pile up in a doc or drafts folder because no step hands them to a person.",
         "Add a human send step: post the draft with an approve/send action to the lead owner, and track sent_at.", _ai_send),
    Rule("no-after-hours", "medium", "No after-hours or weekend coverage",
         "Leads that arrive at night or on weekends wait until the next business day, often past the buyer's patience.",
         "Send an instant acknowledgement with the next reply time, and escalate weekend leads to an on-call person.", _bool("routing.after_hours_coverage")),
    Rule("no-auto-ack", "low", "No instant acknowledgement",
         "Buyers who hear nothing in minutes often contact the next vendor.",
         "Send an automatic confirmation that a named person will reply by a stated time.", _bool("response.auto_ack")),
    Rule("no-dedupe", "low", "Duplicate leads are not merged",
         "Duplicates split history across records; one copy gets answered, the other triggers confusion or double contact.",
         "Dedupe on email/phone when writing to the sheet or CRM.", _bool("storage.dedupe")),
    Rule("tz-mismatch", "medium", "Automation timezone differs from business timezone",
         "Scheduled follow-ups and 'business hours' filters fire at the wrong hour or on the wrong day.",
         "Set the automation account/workflow timezone to the business timezone and store timestamps in ISO 8601 with offset.", _tz),
    Rule("free-plan-limits", "medium", "Automation runs on a free plan",
         "Free tiers cap tasks/operations and polling frequency; when the cap is hit, runs stop until the next cycle.",
         "Check monthly task usage against lead volume and set a usage alert, or move the lead workflow to a paid or self-hosted plan.", _free_plan),
    Rule("no-follow-up", "low", "No follow-up after the first reply",
         "Leads that don't answer the first message are dropped instead of nudged.",
         "Add a 2-3 touch follow-up sequence that stops when the lead replies.", _bool("follow_up.sequence")),
    Rule("no-review", "low", "Run history is never reviewed",
         "Filtered and halted runs accumulate unnoticed.",
         "Review run history weekly, or export it and run analyze_run_history.", lambda c: None if _get(c, "monitoring.run_history_review") is None else str(_get(c, "monitoring.run_history_review")).lower() not in {"never", "no", "false", ""}),
]


def check_config(cfg: dict) -> Report:
    if not isinstance(cfg, dict):
        raise ValueError("pipeline config must be a JSON object")
    rep = Report(pipeline=str(cfg.get("name") or "unnamed pipeline"))
    unknown = 0
    for r in RULES:
        state = r.check(cfg)
        if state is True:
            continue
        if state is False:
            rep.findings.append(Finding(r.id, r.severity, r.title, r.why, r.fix))
        else:
            unknown += 1
            rep.findings.append(Finding(r.id, "verify", f"Not stated: {r.title.lower()}", r.why, r.fix))
    if unknown:
        rep.notes.append(f"{unknown} safeguard(s) were not described; they are listed as 'verify'. Fill them in for a sharper result.")
    return rep


# ---------------- free-text description ----------------

_KW: list[tuple[str, str, Any]] = [
    # (regex, config path, value)
    (r"\b(no ?one|nobody|not assigned|no owner|unassigned|whoever)\b", "routing.owner_assignment", "none"),
    (r"\b(round[- ]?robin|assigned to|owner is|each lead (is )?assigned)\b", "routing.owner_assignment", "assigned"),
    (r"\b(no (error )?alerts?|no notifications? (when|if) .*fail|never (get )?notified)\b", "monitoring.error_alerts", False),
    (r"\b(error (alerts?|notifications?|workflow)|alert(ed)? (me )?(when|if) .*fail)\b", "monitoring.error_alerts", True),
    (r"\b(heartbeat|unanswered[- ]lead alert|sla alert|alert (if|when) .*(not|no) (replied|answered|contacted))\b", "monitoring.unanswered_lead_alert", True),
    (r"\b(google sheets?|spreadsheet|airtable|hubspot|pipedrive|salesforce|zoho|crm|notion)\b", "storage.type", "store"),
    (r"\b(only in (the |my )?(inbox|email|whatsapp|phone)|just (in )?(the )?inbox)\b", "storage.type", "none"),
    (r"\b(free plan|free tier|free account)\b", "automation.plan", "free"),
    (r"\b(paid plan|professional plan|team plan|self[- ]hosted)\b", "automation.plan", "paid"),
    (r"\b(no ?(one|body) (works|answers) (at night|on weekends)|weekends? (are|is) (not covered|uncovered)|no after[- ]hours)\b", "routing.after_hours_coverage", False),
    (r"\b(24/7|on[- ]call|after[- ]hours (coverage|team|rota))\b", "routing.after_hours_coverage", True),
    (r"\b(auto[- ]?(reply|responder|acknowledg\w*)|instant (reply|confirmation))\b", "response.auto_ack", True),
    (r"\b(chatgpt|claude|gpt|openai|ai[- ](draft|reply|replies|writes))\b", "response.ai_drafts", True),
    (r"\b(approve|review(ed)? (the )?(draft|reply) before|human (sends|approves))\b", "response.human_send_step", True),
    (r"\b(follow[- ]?up sequence|follow[- ]?ups?|nurture)\b", "follow_up.sequence", True),
    (r"\b(no follow[- ]?ups?|never follow[- ]?up)\b", "follow_up.sequence", False),
    (r"\b(dedupe|de-duplicate|deduplicat\w*|merge duplicates)\b", "storage.dedupe", True),
]
_SRC = {
    "whatsapp": "whatsapp", "instagram": "instagram_dm", "facebook message": "facebook_dm", "messenger": "facebook_dm",
    "telegram": "telegram", "line ": "line", "kakaotalk": "kakaotalk", "live chat": "chat",
    "typeform": "web_form", "tally": "web_form", "web form": "web_form", "contact form": "web_form", "form": "web_form",
    "lead ads": "ads_lead_form", "lead form": "ads_lead_form", "email": "email", "phone": "phone", "calendly": "booking",
}
_PLATFORM = {"zapier": "zapier", "make.com": "make", "make scenario": "make", "integromat": "make", "n8n": "n8n"}


def _set(cfg: dict, path: str, value: Any) -> None:
    parts = path.split(".")
    cur = cfg
    for p in parts[:-1]:
        cur = cur.setdefault(p, {})
    cur[parts[-1]] = value


def config_from_text(text: str) -> dict:
    t = " " + re.sub(r"\s+", " ", text.lower()) + " "
    cfg: dict[str, Any] = {"name": "described pipeline"}
    for pattern, path, value in _KW:
        if re.search(pattern, t):
            if _get(cfg, path) in (False, "none"):
                continue  # an explicit negative ("nobody", "no error alerts") wins over a later generic match
            _set(cfg, path, value)
    m = re.search(r"\b(?:within|in under|under|in)\s+(\d{1,4})\s*(min|minutes|h|hours?)\b", t)
    if m:
        n = int(m.group(1)) * (60 if m.group(2).startswith("h") else 1)
        _set(cfg, "response.sla_minutes", n)
    srcs, seen = [], set()
    for k, v in _SRC.items():
        if re.search(r"\b" + re.escape(k.strip()) + r"s?\b", t) and v not in seen:
            seen.add(v)
            srcs.append({"type": v})
    if srcs:
        cfg["sources"] = srcs
    for k, v in _PLATFORM.items():
        if k in t:
            _set(cfg, "automation.platform", v)
            break
    if "storage" in cfg and cfg["storage"].get("type") == "store":
        for s in srcs:
            if s["type"] in {"whatsapp", "instagram_dm", "facebook_dm", "telegram", "line", "kakaotalk", "chat"}:
                s["logged_to_storage"] = None
    return cfg


def check_description(text: str) -> Report:
    if not text or not text.strip():
        raise ValueError("description is empty: describe where leads come from, where they are stored, who replies, and what alerts exist")
    cfg = config_from_text(text)
    rep = check_config(cfg)
    rep.pipeline = "described pipeline"
    rep.notes.insert(0, "Parsed from free text with keyword rules; send a JSON config (see check_pipeline) for exact results.")
    rep.notes.append("Interpreted as: " + _flat(cfg))
    return rep


def _flat(cfg: dict, prefix: str = "") -> str:
    parts = []
    for k, v in cfg.items():
        if k == "name":
            continue
        if isinstance(v, dict):
            parts.append(_flat(v, f"{prefix}{k}."))
        elif isinstance(v, list):
            parts.append(f"{prefix}{k}=[{', '.join(str(x.get('type', x)) if isinstance(x, dict) else str(x) for x in v)}]")
        else:
            parts.append(f"{prefix}{k}={v}")
    return "; ".join(p for p in parts if p)


# ---------------- run history ----------------

_STATUS_COLS = ("status", "state", "result", "outcome")
_TIME_COLS = ("timestamp", "date", "time", "started_at", "start", "created_at", "run_at", "datetime", "executed_at")
_BAD = {"error", "errored", "failed", "failure", "halted", "stopped", "crashed", "timeout", "warning"}
_SKIPPED = {"filtered", "skipped", "held", "throttled", "playback", "ignored"}


def _parse_ts(s: str) -> datetime | None:
    s = s.strip()
    if not s:
        return None
    if re.fullmatch(r"\d{10}(\d{3})?", s):
        n = int(s)
        return datetime.fromtimestamp(n / 1000 if n > 1e12 else n, tz=timezone.utc)
    try:
        d = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        d = None
        for fmt in ("%m/%d/%Y %H:%M:%S", "%m/%d/%Y %H:%M", "%d/%m/%Y %H:%M", "%Y-%m-%d %H:%M", "%b %d, %Y %I:%M %p", "%B %d, %Y %I:%M %p"):
            try:
                d = datetime.strptime(s, fmt)
                break
            except ValueError:
                continue
    if d is None:
        return None
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def analyze_history(csv_text: str, expected_interval_minutes: float | None = None, now: datetime | None = None) -> Report:
    rows = list(csv.DictReader(io.StringIO(csv_text.strip())))
    if not rows:
        raise ValueError("run history CSV has no data rows; export it with a header row (status, timestamp)")
    cols = {c.lower().strip(): c for c in rows[0].keys() if c}
    scol = next((cols[c] for c in _STATUS_COLS if c in cols), None)
    tcol = next((cols[c] for c in _TIME_COLS if c in cols), None)
    if not scol:
        raise ValueError(f"no status column found; expected one of {', '.join(_STATUS_COLS)}; got {', '.join(cols)}")
    rep = Report(pipeline="run history")
    statuses = [str(r.get(scol, "")).strip().lower() for r in rows]
    total = len(statuses)
    bad = sum(1 for s in statuses if s in _BAD)
    skipped = sum(1 for s in statuses if s in _SKIPPED)
    rep.notes.append(f"{total} runs: {total - bad - skipped} ok, {bad} failed/halted, {skipped} filtered/skipped.")
    if bad:
        sev = "high" if bad / total >= 0.05 or bad >= 3 else "medium"
        rep.findings.append(Finding("failed-runs", sev, f"{bad} failed or halted run{'s' if bad != 1 else ''}",
                                    "Every failed run after the trigger is a lead that may never have been stored, routed or answered.",
                                    "Replay the failed runs, then add an error alert so the next failure is seen within minutes.",
                                    f"{bad}/{total} runs ({bad / total:.0%})"))
    if skipped:
        sev = "medium" if skipped / total >= 0.1 else "low"
        rep.findings.append(Finding("filtered-runs", sev, f"{skipped} run{'s were' if skipped != 1 else ' was'} filtered or skipped",
                                    "Filtered runs end without an error. If the filter keys on an empty or renamed field, real leads are dropped.",
                                    "Open a sample of filtered runs; route them to a 'needs review' list instead of stopping.",
                                    f"{skipped}/{total} runs ({skipped / total:.0%})"))
    if tcol:
        times = sorted(t for t in (_parse_ts(str(r.get(tcol, ""))) for r in rows) if t)
        if len(times) < len(rows):
            rep.notes.append(f"{len(rows) - len(times)} timestamp(s) could not be parsed.")
        if len(times) >= 3:
            gaps = [(b - a).total_seconds() / 60 for a, b in zip(times, times[1:])]
            med = statistics.median(gaps)
            ref = expected_interval_minutes or med
            biggest = max(gaps)
            i = gaps.index(biggest)
            if ref > 0 and biggest >= max(ref * 6, 120):
                rep.findings.append(Finding("run-gap", "high" if biggest >= 24 * 60 else "medium",
                                            f"No runs for {biggest / 60:.1f} hours",
                                            "A long gap usually means the workflow was off, a connection expired, or a plan limit was hit while leads kept arriving.",
                                            "Check what happened in that window and add an alert when no run occurs within the expected interval.",
                                            f"{times[i].isoformat()} -> {times[i + 1].isoformat()} (typical gap {med:.0f} min)"))
            now = now or datetime.now(timezone.utc)
            since = (now - times[-1]).total_seconds() / 60
            if ref > 0 and since >= max(ref * 6, 120):
                rep.findings.append(Finding("stale", "high", f"Last run was {since / 60:.1f} hours ago",
                                            "The workflow may be switched off right now.",
                                            "Open the workflow, confirm it is on, and test it with a real submission.",
                                            f"last run {times[-1].isoformat()}"))
    else:
        rep.notes.append("No timestamp column found, so gaps and stale workflows could not be checked.")
    return rep
